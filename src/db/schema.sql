-- ============================================================
-- TABLE: perfiles_agresores
-- Mathematical behavior vectors ONLY. Zero victim data here.
-- ============================================================

create table perfiles_agresores (
  id             uuid           primary key default gen_random_uuid(),
  patron_vector  vector(768)    not null,      -- Google text-embedding-004 dimensions
  plataformas    text[]         not null,      -- ['Instagram', 'Roblox', 'Free Fire']
  tacticas       text[]         not null,      -- ['love_bombing', 'aislamiento', 'solicitud_imagen']
  -- JSONB schema:
  -- {
  --   "franjas": [{"dias_semana": [0-6], "hora_inicio": "HH:MM", "hora_fin": "HH:MM"}],
  --   "zona_horaria_estimada": "America/Mexico_City",
  --   "hora_pico": "HH:MM" | null
  -- }
  horarios       jsonb          not null default '{"franjas":[],"zona_horaria_estimada":"America/Mexico_City","hora_pico":null}',
  nivel_riesgo   nivel_riesgo_t not null default 'medio',
  num_reportes   int            not null default 1,
  created_at     timestamptz    not null default now(),
  updated_at     timestamptz    not null default now()
);

-- HNSW index: works with zero initial data, ideal for a fresh database
create index perfiles_agresores_hnsw_idx
  on perfiles_agresores
  using hnsw (patron_vector vector_cosine_ops)
  with (m = 16, ef_construction = 64);

create index perfiles_agresores_plataformas_idx
  on perfiles_agresores using gin (plataformas);

-- ============================================================
-- TABLE: alertas
-- Auto-generated by AI when patterns are detected.
-- ============================================================

create table alertas (
  id              uuid             primary key default gen_random_uuid(),
  nivel_urgencia  nivel_urgencia_t not null,
  num_victimas    int              not null default 1,
  perfil_id       uuid             references perfiles_agresores(id) on delete set null,
  plataformas     text[]           not null,
  zona_geografica text,
  horarios        jsonb            not null default '{"franjas":[],"zona_horaria_estimada":"America/Mexico_City","hora_pico":null}',
  estado          estado_alerta_t  not null default 'nueva',
  created_at      timestamptz      not null default now(),
  updated_at      timestamptz      not null default now()
);

create index alertas_estado_idx     on alertas (estado);
create index alertas_urgencia_idx   on alertas (nivel_urgencia);
create index alertas_created_idx    on alertas (created_at desc);

-- ============================================================
-- TABLE: reportes_directos
-- Voluntary victim reports. Separated from alertas by design.
-- ============================================================

create table reportes_directos (
  id               uuid             primary key default gen_random_uuid(),
  folio            text             not null unique,  -- 'A-XXXXXX' format
  hash_sha256      text             not null,
  tsa_token        text,            -- RFC 3161 timestamp token (base64), nullable if FreeTSA unavailable
  tsa_timestamp    timestamptz,
  plataforma       text             not null,
  tipo             text             not null,         -- 'sextorsion' | 'grooming' | 'acoso'
  patrones         text[]           not null,
  -- JSONB schema:
  -- {
  --   "plataformas": ["Instagram", "WhatsApp"],
  --   "identificadores": ["@kevindiaz_mx", "5512345678"],  -- any platform identifier
  --   "telefono": "+52 55 1234 5678",                       -- plain text (it's evidence, not PII)
  --   "pais_estimado": "MX",
  --   "horario_contacto": {"hora_inicio": "HH:MM", "hora_fin": "HH:MM"},
  --   "tacticas": ["love_bombing", "aislamiento", "solicitud_imagen"],
  --   "fase_grooming": 1-5,
  --   "descripcion_libre": null | "texto opcional"
  -- }
  perfil_agresor   jsonb            not null,
  -- AES-256-GCM encrypted email. Format: "base64(iv):base64(ciphertext)"
  -- Null if victim chose not to share contact info.
  contacto_cifrado text,
  -- AES-256-GCM encrypted JSON: {nombre, contacto}. Only populated in ruta legal.
  contacto_familiar_cifrado text,
  -- 'privado' = just a record, no one is contacted
  -- 'legal'   = ANCLA agent contacts the family and opens a formal process
  tipo_reporte     text             not null default 'privado'
                     check (tipo_reporte in ('privado', 'legal')),
  -- NULL = not asked (privado), TRUE = implicit (legal — youth provided family contact)
  adulto_al_tanto  boolean          default null,
  alerta_id        uuid             references alertas(id) on delete set null,
  estado           estado_reporte_t not null default 'nuevo',
  created_at       timestamptz      not null default now(),
  updated_at       timestamptz      not null default now()
);

create index reportes_directos_estado_idx   on reportes_directos (estado);
create index reportes_directos_created_idx  on reportes_directos (created_at desc);
create index reportes_directos_alerta_idx   on reportes_directos (alerta_id);

-- ============================================================
-- TABLE: vinculaciones
-- M:M between alertas and reportes_directos with similarity score.
-- ============================================================

create table vinculaciones (
  id              uuid        primary key default gen_random_uuid(),
  alerta_id       uuid        not null references alertas(id) on delete cascade,
  reporte_id      uuid        not null references reportes_directos(id) on delete cascade,
  similitud_score float       not null check (similitud_score >= 0 and similitud_score <= 1),
  confirmada      boolean     not null default false,
  created_at      timestamptz not null default now(),
  unique (alerta_id, reporte_id)
);

