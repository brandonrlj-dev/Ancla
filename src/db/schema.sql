-- Helper: true if the current JWT belongs to a police agent
create or replace function es_agente_policial()
returns bool
language sql stable security definer
as $$
  select coalesce(
    (auth.jwt() -> 'user_metadata' ->> 'rol') = 'policia',
    false
  )
$$;

-- perfiles_agresores: agents read; service_role writes (no INSERT policy = only service_role)
create policy "agentes_ven_perfiles" on perfiles_agresores
  for select using (es_agente_policial());

-- alertas: agents read; agents can update estado; service_role inserts
create policy "agentes_ven_alertas" on alertas
  for select using (es_agente_policial());
create policy "agentes_actualizan_alertas" on alertas
  for update using (es_agente_policial()) with check (es_agente_policial());

-- reportes_directos: agents read; service_role inserts
create policy "agentes_ven_reportes" on reportes_directos
  for select using (es_agente_policial());

-- vinculaciones: agents read
create policy "agentes_ven_vinculaciones" on vinculaciones
  for select using (es_agente_policial());

-- jobs_analisis: no JWT access (service_role only via no policies)

-- audit_log: each agent sees own rows; no updates/deletes (enforced by triggers above)
create policy "agentes_ven_su_audit" on audit_log
  for select using (agente_id = auth.uid());

-- config_plataformas: agents read
create policy "agentes_ven_config" on config_plataformas
  for select using (es_agente_policial());

-- push_suscripciones: agents manage their own
create policy "agentes_ven_sus_suscripciones" on push_suscripciones
  for select using (agente_id = auth.uid());
create policy "agentes_insertan_suscripcion" on push_suscripciones
  for insert with check (agente_id = auth.uid());
create policy "agentes_borran_su_suscripcion" on push_suscripciones
  for delete using (agente_id = auth.uid());

-- ============================================================
-- FUNCTION: incrementar_victimas
-- Atomic num_victimas++ — avoids read-then-write race condition.
-- ============================================================

create or replace function incrementar_victimas(p_alerta_id uuid)
returns void
language sql security definer
as $$
  update alertas
  set num_victimas = num_victimas + 1, updated_at = now()
  where id = p_alerta_id;
$$;

