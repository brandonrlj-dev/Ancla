-- ============================================================
-- FUNCTION: buscar_perfil_similar
-- Cosine similarity search with per-platform configurable threshold.
-- security definer so it runs as owner and can read all rows.
-- ============================================================

create or replace function buscar_perfil_similar(
  p_embedding  vector(768),
  p_plataforma text
)
returns table (
  perfil_id    uuid,
  similitud    float,
  num_reportes int,
  nivel_riesgo nivel_riesgo_t
)
language plpgsql stable security definer
as $$
declare
  v_umbral float := 0.82;
begin
  select umbral_similitud into v_umbral
  from config_plataformas
  where plataforma = p_plataforma and activo = true
  limit 1;

  return query
  select
    pa.id,
    1 - (pa.patron_vector <=> p_embedding) as similitud,
    pa.num_reportes,
    pa.nivel_riesgo
  from perfiles_agresores pa
  where
    pa.plataformas && array[p_plataforma]
    and 1 - (pa.patron_vector <=> p_embedding) >= coalesce(v_umbral, 0.82)
  order by similitud desc
  limit 5;
end;
$$;

-- ============================================================
-- FUNCTION: vincular_reporte_a_alerta
-- Called after a new report is processed. Links to the most
-- recent open alert from the same aggressor profile.
-- ============================================================

create or replace function vincular_reporte_a_alerta(
  p_reporte_id uuid,
  p_perfil_id  uuid,
  p_similitud  float
)
returns void
language plpgsql security definer
as $$
declare
  v_alerta_id uuid;
begin
  select id into v_alerta_id
  from alertas
  where perfil_id = p_perfil_id
    and estado not in ('resuelta', 'archivada')
  order by created_at desc
  limit 1;

  if v_alerta_id is not null then
    insert into vinculaciones (alerta_id, reporte_id, similitud_score)
    values (v_alerta_id, p_reporte_id, p_similitud)
    on conflict (alerta_id, reporte_id) do nothing;

    update reportes_directos
    set alerta_id = v_alerta_id, updated_at = now()
    where id = p_reporte_id;

    update alertas
    set num_victimas = num_victimas + 1, updated_at = now()
    where id = v_alerta_id;
  end if;
end;
$$;

