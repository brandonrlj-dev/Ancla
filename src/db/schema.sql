-- ============================================================
-- TABLE: jobs_analisis
-- Resilience for long Claude analysis. 15-minute TTL by design.
-- ============================================================

create table jobs_analisis (
  id             uuid         primary key default gen_random_uuid(),
  -- Ephemeral token generated client-side. Never linked to any identity.
  session_token  text         not null,
  estado         estado_job_t not null default 'pendiente',
  -- Input data for processAnalysisJob (stored here so after() can access it)
  -- Schema: { "ocrText": "...", "conversationContext": "..." }
  payload        jsonb        not null,
  resultado      jsonb,       -- null until estado = 'completado'
  error_msg      text,        -- null until estado = 'fallido'
  intentos       int          not null default 0,
  creado_en      timestamptz  not null default now(),
  actualizado_en timestamptz  not null default now(),
  expira_en      timestamptz  not null default (now() + interval '15 minutes')
);

create index jobs_analisis_token_idx  on jobs_analisis (session_token);
create index jobs_analisis_expiry_idx on jobs_analisis (expira_en);

-- Auto-cleanup of expired jobs every 5 minutes
select cron.schedule(
  'cleanup-expired-analysis-jobs',
  '*/5 * * * *',
  $$delete from jobs_analisis where expira_en < now()$$
);

